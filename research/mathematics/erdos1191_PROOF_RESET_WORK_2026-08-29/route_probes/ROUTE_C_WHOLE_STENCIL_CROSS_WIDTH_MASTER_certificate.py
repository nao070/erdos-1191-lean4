def _projected_width_slack(
    width: int,
    rows: Sequence[tuple[int, int, int]],
) -> tuple[tuple[F, ...], ...]:
    indices = tuple(
        index
        for index, (_, channel_width, _) in enumerate(base.CHANNELS)
        if channel_width == width
    )
    if len(indices) != 13:
        raise CertificateError("width block size changed")
    gram = base._physical_gram_q()
    slack = [[gram[i][j] for j in indices] for i in indices]
    _, cells, _ = base._geometry()
    for row, numerator, denominator in rows:
        weight = F(numerator, denominator)
        if weight <= 0:
            raise CertificateError("dual weight is not positive")
        owner = base.OWNER_ORDER[row // len(cells)]
        if owner[1] != width:
            raise CertificateError("dual row assigned to the wrong width")
        for local_i, i in enumerate(indices):
            for local_j, j in enumerate(indices):
                slack[local_i][local_j] -= (
                    weight * base._psd_row_matrix_entry(row, i, j)
                )
    last = len(indices) - 1
    return tuple(
        tuple(
            slack[i][j]
            - slack[i][last]
            - slack[last][j]
            + slack[last][last]
            for j in range(last)
        )
        for i in range(last)
    )


