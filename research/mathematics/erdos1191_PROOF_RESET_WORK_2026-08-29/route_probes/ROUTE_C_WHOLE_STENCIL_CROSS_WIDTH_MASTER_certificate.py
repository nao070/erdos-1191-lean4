class CertificateError(RuntimeError):
    """Raised when an exact identity, witness, dual, or scope gate fails."""


def ftext(value: F | int) -> str:
    value = F(value)
    return f"{value.numerator}/{value.denominator}"


def _canonical_hash(value: object) -> str:
    raw = json.dumps(
        value,
        sort_keys=True,
        separators=(",", ":"),
        ensure_ascii=False,
    ).encode("utf-8")
    return hashlib.sha256(raw).hexdigest()


def _assert_equal(actual: object, expected: object, message: str) -> None:
    if actual != expected:
        raise CertificateError(message)


def _positive_ldl_pivots(matrix: Sequence[Sequence[F]]) -> tuple[F, ...]:
    size = len(matrix)
    if any(len(row) != size for row in matrix):
        raise CertificateError("LDL matrix is not square")
    lower = [[F(0) for _ in range(size)] for _ in range(size)]
    diagonal: list[F] = []
    for i in range(size):
        for j in range(i):
            residual = matrix[i][j] - sum(
                (
                    lower[i][k] * diagonal[k] * lower[j][k]
                    for k in range(j)
                ),
                F(0),
            )
            if diagonal[j] == 0:
                raise CertificateError("zero LDL pivot")
            lower[i][j] = residual / diagonal[j]
        pivot = matrix[i][i] - sum(
            (lower[i][k] * lower[i][k] * diagonal[k] for k in range(i)),
            F(0),
        )
        if pivot <= 0:
            raise CertificateError(f"nonpositive LDL pivot at {i}")
        diagonal.append(pivot)
        lower[i][i] = F(1)
    return tuple(diagonal)


def _validate_z(
    numerators: Sequence[Sequence[int]],
    expected_size: int,
) -> tuple[tuple[F, ...], ...]:
    if len(numerators) != expected_size:
        raise CertificateError("epoch Z row count changed")
    if any(len(row) != expected_size for row in numerators):
        raise CertificateError("epoch Z column count changed")
    if any(type(value) is not int for row in numerators for value in row):
        raise CertificateError("epoch Z contains a noninteger numerator")
    for i in range(expected_size):
        for j in range(expected_size):
            if numerators[i][j] != numerators[j][i]:
                raise CertificateError("epoch Z is not symmetric")
    matrix = tuple(
        tuple(F(value, Z_DENOMINATOR) for value in row)
        for row in numerators
    )
    _positive_ldl_pivots(matrix)
    return matrix


def _zero_sum_extension(
    numerators: Sequence[Sequence[int]],
) -> tuple[tuple[int, ...], ...]:
    rank = len(numerators)
    size = rank + 1
    matrix = [[0 for _ in range(size)] for _ in range(size)]
    for i in range(rank):
        for j in range(rank):
            matrix[i][j] = numerators[i][j]
    for i in range(rank):
        matrix[i][rank] = -sum(numerators[i])
        matrix[rank][i] = -sum(numerators[j][i] for j in range(rank))
    matrix[rank][rank] = sum(sum(row) for row in numerators)
    if any(sum(row) != 0 for row in matrix):
        raise CertificateError("zero-sum extension failed")
    return tuple(tuple(row) for row in matrix)


def _epoch_indices(n: int) -> tuple[int, ...]:
    if n == 4:
        return tuple(
            index
            for index, (rank, _, _) in enumerate(base.CHANNELS)
            if rank <= 7
        )
    if n == 8:
        return tuple(
            index
            for index, (rank, _, _) in enumerate(base.CHANNELS)
            if rank >= 8
        )
    raise ValueError("only the n=4 and n=8 fixture epochs are defined")


def _embedded_epoch_blocks() -> tuple[
    tuple[tuple[int, ...], ...],
    dict[int, tuple[tuple[int, ...], ...]],
]:
    _validate_z(Z4_NUMERATORS, 19)
    _validate_z(Z8_NUMERATORS, 31)
    local = {
        4: _zero_sum_extension(Z4_NUMERATORS),
        8: _zero_sum_extension(Z8_NUMERATORS),
    }
    size = len(base.CHANNELS)
    global_matrix = [[0 for _ in range(size)] for _ in range(size)]
    for n, block in local.items():
        indices = _epoch_indices(n)
        if len(indices) != len(block):
            raise CertificateError("epoch block dimension changed")
        for i, global_i in enumerate(indices):
            for j, global_j in enumerate(indices):
                global_matrix[global_i][global_j] = block[i][j]
    return tuple(tuple(row) for row in global_matrix), local


def _overlap(width: int, distance: int) -> F:
    if distance >= width:
        return F(0)
    return F(width - distance, width * width)


def _sources(n: int) -> tuple[tuple[int, int], ...]:
    return tuple(
        (i, j)
        for j in range(n + 2, 2 * n)
        for i in range(n, j - 1)
    )


def _alpha(n: int, i: int, j: int) -> F:
    return F((j - i) ** 2, 4 * n * n)


def _psi(n: int, i: int, j: int, width: int) -> F:
    middle = base.POINTS[j - 1] - base.POINTS[i]
    left = base.POINTS[i] - base.POINTS[i - 1]
    right = base.POINTS[j] - base.POINTS[j - 1]
    return (
        _overlap(width, middle)
        + _overlap(width, middle + left + right)
        - _overlap(width, middle + left)
        - _overlap(width, middle + right)
    )


def _primitive_capacity(n: int, i: int, j: int) -> F:
    widths = (100, 200, 400, 800)
    return sum(
        (
            F(2 * width)
            * _alpha(n, i, j)
            * (_psi(n, i, j, width) - _psi(n, i, j, 2 * width))
            for width in widths
        ),
        F(0),
    )


def _primitive_cell_demand(
    n: int,
    i: int,
    j: int,
    width: int,
    cell: tuple[int, int],
) -> F:
    _, cells, q_states = base._geometry()
    q = q_states[cells.index(cell)]
    indices = base._owner_full_indices((n, width))
    h = tuple(F(q[index], 1600) for index in indices)
    left_gap = i - n
    right_gap = j - n
    return (
        F(2 * width)
        * -_alpha(n, i, j)
        * (h[left_gap] - h[left_gap + 1])
        * (h[right_gap] - h[right_gap + 1])
    )


